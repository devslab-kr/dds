import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
test('Vue controls, owned overlays and native Community grid interactions', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('combobox', { name: '거래처 검색', exact: true }).fill('서울')
  await page.getByRole('listbox', { name: '거래처 검색' }).getByRole('option', { name: '서울' }).click()
  await page.getByRole('button', { name: '값 늘리기' }).click()
  await expect(page.getByRole('spinbutton', { name: '수량' })).toHaveAttribute('aria-valuenow', '2')
  await page.getByRole('tab', { name: '추가', exact: true }).click()
  await expect(page.getByText('추가 탭 내용')).toBeVisible()
  await page.getByRole('button', { name: '대화상자 열기' }).click()
  const dialog = page.getByRole('dialog', { name: '변경 확인' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('combobox', { name: '대화상자 지역' }).click()
  await expect(dialog.getByRole('option', { name: '부산' })).toBeVisible()
  await page.keyboard.press('Escape'); await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape'); await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).last().click()
  await page.getByRole('menuitem', { name: '새 항목' }).click()
  await expect(page.getByLabel('메뉴 결과')).toHaveText('new')
  await page.getByRole('button', { name: '토스트 표시' }).click()
  await expect(page.getByRole('status').filter({ hasText: '저장 완료' })).toBeVisible()
  await page.getByRole('button', { name: '알림 닫기' }).click()
  await page.getByRole('button', { name: '기간 달력 열기', exact: true }).click()
  const rangeCalendar = page.getByRole('application', { name: '기간 선택', exact: true })
  await rangeCalendar.getByRole('button', { name: '2026년 10월 10일 토요일' }).click()
  await rangeCalendar.getByRole('button', { name: '2026년 10월 15일 목요일' }).click()
  await expect(page.getByRole('textbox', { name: '시작일', exact: true })).toHaveValue('2026/10/10')
  await expect(page.getByRole('textbox', { name: '종료일', exact: true })).toHaveValue('2026/10/15')
  const grid = page.getByRole('grid', { name: '샘플 거래처' })
  await expect(grid).toBeVisible()
  const amountHeader = grid.getByRole('columnheader', { name: '금액' })
  await amountHeader.getByText('금액', { exact: true }).click()
  await expect(amountHeader).toHaveAttribute('aria-sort', 'ascending')
  await expect(grid.locator('[row-index="0"] [col-id="amount"]')).toHaveText('100')
  await page.getByRole('button', { name: '행 추가', exact: true }).click()
  await expect(page.getByText('전체 4건', { exact: false })).toBeVisible()
  await expect(grid.locator('[row-id="d"]')).toBeVisible()
  await grid.locator('[row-id="b"] .ag-selection-checkbox input').check()
  await expect(page.getByText('표 선택 1건', { exact: false })).toBeVisible()
  const resize = amountHeader.locator('.ag-header-cell-resize')
  const before = await amountHeader.boundingBox()
  const handle = await resize.boundingBox()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2)
  await page.mouse.down(); await page.mouse.move(handle!.x - 60, handle!.y + handle!.height / 2); await page.mouse.up()
  await expect.poll(async () => (await amountHeader.boundingBox())!.width).toBeLessThan(before!.width - 30)
  await amountHeader.focus(); await page.keyboard.press('Control+Enter')
  const filter = page.getByRole('spinbutton', { name: 'Filter Value' })
  await filter.fill('200')
  await expect(grid.getByRole('gridcell', { name: '200', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: '100', exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
})
test('Vue showcase is accessible and does not overflow at desktop widths', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('grid', { name: '샘플 거래처' })).toBeVisible()
  for (const width of [1440, 1024]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  for (const theme of ['light', 'dark']) {
    await page.getByRole('switch', { name: '다크 테마' }).setChecked(theme === 'dark')
    const results = await new AxeBuilder({ page }).analyze()
    expect(results.violations).toEqual([])
  }
})

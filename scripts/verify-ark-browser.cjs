async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.getByRole('textbox', {name:'Retained note'}).fill('Kept note');
  await page.getByRole('button', {name:'Disable second tab'}).click();
  await page.getByRole('tab', {name:'First tab', exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => document.querySelector('[role="tab"][aria-selected="true"]')?.textContent === 'Third tab');
  await page.getByRole('tab', {name:'First tab', exact:true}).click();
  check(await page.getByRole('textbox', {name:'Retained note'}).inputValue() === 'Kept note', 'Retained panel lost its input');
  await page.getByRole('radio', {name:'Choice A', exact:true}).focus();
  await page.keyboard.press('ArrowDown');
  check(await page.getByRole('radio', {name:'Choice B', exact:true}).isChecked(), 'Radio group arrow navigation failed');
  const entries = await page.locator('#controls').evaluate(form => Object.fromEntries(new FormData(form)));
  check(entries.agree === 'on' && entries.enabled === 'on' && entries.choice === 'b' && entries.country === 'kr', 'Native form values lost');
  await page.locator('#controls').evaluate(form => form.reset());
  const resetEntries = await page.locator('#controls').evaluate(form => Object.fromEntries(new FormData(form)));
  check(resetEntries.agree === 'on' && resetEntries.enabled === 'on' && resetEntries.choice === 'a', 'Native form reset lost defaults');
  await page.getByRole('button', {name:'Open dialog', exact:true}).click();
  const dialog = page.getByRole('dialog', {name:'Confirmation'});
  await dialog.waitFor();
  check(await page.getByRole('button', {name:'First action', exact:true}).evaluate(el => el === document.activeElement), 'Dialog initial focus failed');
  await page.getByRole('button', {name:'Close dialog', exact:true}).focus();
  await page.keyboard.press('Tab');
  check(await page.getByRole('button', {name:'First action', exact:true}).evaluate(el => el === document.activeElement), 'Dialog forward focus trap failed');
  await page.keyboard.press('Shift+Tab');
  check(await page.getByRole('button', {name:'Close dialog', exact:true}).evaluate(el => el === document.activeElement), 'Dialog backward focus trap failed');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  check(await page.getByRole('button', {name:'Open dialog', exact:true}).evaluate(el => el === document.activeElement), 'Dialog focus restoration failed');
  await page.keyboard.press('Tab');
  await page.getByRole('button', {name:'Help trigger', exact:true}).focus();
  await page.getByRole('tooltip').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  await page.getByRole('tooltip').waitFor({state:'hidden'});
  await page.getByRole('button', {name:'Show toast', exact:true}).click();
  await page.getByRole('status').waitFor();
  const toastBox = await page.getByRole('status').boundingBox();
  const viewport = page.viewportSize();
  check(toastBox && viewport && toastBox.x >= 0 && toastBox.y >= 0 && toastBox.x + toastBox.width <= viewport.width && toastBox.y + toastBox.height <= viewport.height, 'Toast exceeds viewport');
  await page.getByRole('status').waitFor({state:'hidden',timeout:5000});
  await page.getByRole('button', {name:'Show secondary toast',exact:true}).click();
  await page.getByRole('button', {name:'Open dialog',exact:true}).click();
  await page.getByRole('dialog', {name:'Confirmation'}).waitFor();
  await page.getByRole('button', {name:'Close secondary notification',exact:true}).click();
  check(await page.getByRole('dialog', {name:'Confirmation'}).isVisible(), 'Second toaster was treated as a dialog outside click');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', {name:'Confirmation'}).waitFor({state:'hidden'});
  return {tabs:'passed',retention:'passed',form:entries,reset:'passed',dialog:'passed',tooltip:'passed',toast:'passed',multipleProviders:'passed',viewport};
}

/**
 * Android token generator — tokens/*.json → Kotlin constants + XML resources
 * for android/dds-tokens (kr.devslab:dds-android-tokens).
 *
 *   node scripts/generate-android-tokens.mjs           write the files
 *   node scripts/generate-android-tokens.mjs --check   fail if a committed file differs
 *
 * The output is committed so the Gradle build never needs Node. The price of a
 * committed artifact is drift, so tests/android-tokens.test.mjs and `--check`
 * (in `pnpm run check`) regenerate and compare byte for byte.
 *
 * Every $type has an explicit rendering; an unknown one is a build error.
 *
 * Deliberately not emitted:
 *   - the raw palette (apps may only use semantic tokens — what is not shipped
 *     cannot be used; same rule as tokens.css),
 *   - the @devslab/dds-tokens version (it changes on every web release, which
 *     would make the automated release PR fail the drift check). The content
 *     hash of the token files identifies the source instead.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { resolveTokenDocuments } from "../packages/dds-tokens/resolve.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokensDir = join(root, "tokens");

const LIGHT_SOURCES = ["palette.json", "foundation.json", "semantic.light.json", "native.json"];
const DARK_SOURCES = ["palette.json", "semantic.dark.json"];
const KOTLIN_DIR = "android/dds-tokens/src/main/kotlin/kr/devslab/dds/tokens";
const RES_DIR = "android/dds-tokens/src/main/res";
const PACKAGE = "kr.devslab.dds.tokens";

export const GENERATED_HEADER = "Generated by scripts/generate-android-tokens.mjs — do not edit.";

// ---------------------------------------------------------------------------
// Value rendering
// ---------------------------------------------------------------------------

const where = (t) => t.path.join(".");

function expectType(t, ...types) {
  if (!types.includes(t.$type)) {
    throw new Error(`No Android rendering for $type "${t.$type}" at ${where(t)} (expected ${types.join(" or ")})`);
  }
}

/** "#rrggbb" | "#rrggbbaa" (web order) → "AARRGGBB". */
function argb(t) {
  expectType(t, "color");
  const hex = String(t.$value).replace(/^#/, "");
  if (!/^(?:[0-9a-f]{6}|[0-9a-f]{8})$/i.test(hex)) throw new Error(`Not a hex color at ${where(t)}: ${t.$value}`);
  const upper = hex.toUpperCase();
  return upper.length === 8 ? upper.slice(6) + upper.slice(0, 6) : `FF${upper}`;
}

function wholeNumber(t, value) {
  if (!Number.isInteger(value)) throw new Error(`Expected a whole number at ${where(t)}: ${JSON.stringify(t.$value)}`);
  return value;
}

const dimension = (t) => (expectType(t, "dimension"), wholeNumber(t, t.$value));
const count = (t) => (expectType(t, "number"), wholeNumber(t, t.$value));

function millis(t) {
  expectType(t, "duration");
  const match = /^(\d+)ms$/.exec(String(t.$value));
  if (!match) throw new Error(`Expected "<n>ms" at ${where(t)}: ${t.$value}`);
  return Number(match[1]);
}

function easing(t) {
  expectType(t, "cubicBezier");
  if (!Array.isArray(t.$value) || t.$value.length !== 4) throw new Error(`Expected four control points at ${where(t)}`);
  return `DdsEasingToken(${t.$value.map((n) => `${n}f`).join(", ")})`;
}

function typography(t) {
  expectType(t, "typography");
  const { fontSize, lineHeight, fontWeight } = t.$value;
  return `DdsTypeToken(${wholeNumber(t, fontSize)}, ${wholeNumber(t, lineHeight)}, ${wholeNumber(t, fontWeight)})`;
}

const camel = (segments) =>
  segments
    .join("-")
    .split("-")
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
const pascal = (segments) => {
  const c = camel(segments);
  return c[0].toUpperCase() + c.slice(1);
};
const snake = (segments) => segments.join("_").replaceAll("-", "_");
/** Kotlin identifiers cannot start with a digit: space.16 → s16. */
const ident = (prefix, name) => (/^\d/.test(name) ? `${prefix}${name}` : name);

const kotlinFile = (body) => `// ${GENERATED_HEADER} Source: tokens/*.json\npackage ${PACKAGE}\n\n${body.trimEnd()}\n`;

function kotlinObject(name, doc, lines) {
  return `/** ${doc} */\nobject ${name} {\n${lines.map((l) => `    ${l}`).join("\n")}\n}\n`;
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

/**
 * @param {{ light: object[], dark: object[], sourceSha256: string }} input parsed token documents
 * @returns {Map<string, string>} repo-relative path → file content
 */
export function renderAndroidTokens({ light, dark, sourceSha256 }) {
  const lightTokens = resolveTokenDocuments(light);
  const darkTokens = resolveTokenDocuments(dark);
  const claimed = new Set();
  const take = (tokens, ...prefix) => {
    const found = tokens.filter((t) => prefix.every((segment, i) => t.path[i] === segment));
    for (const t of found) claimed.add(t);
    return found;
  };
  const one = (...path) => {
    const [token] = take(lightTokens, ...path).filter((t) => t.path.length === path.length);
    if (!token) throw new Error(`Token not found: ${path.join(".")}`);
    return token;
  };

  // The palette and the web-only tokens are read (references resolve through
  // them) but not shipped.
  take(lightTokens, "palette");
  take(lightTokens, "font");
  for (const t of take(lightTokens, "elevation")) expectType(t, "shadow");

  // --- colors -------------------------------------------------------------
  const lightColors = take(lightTokens, "color");
  const darkColors = darkTokens.filter((t) => t.path[0] === "color");
  const names = (tokens) => tokens.map((t) => where(t)).sort().join("\n");
  if (names(lightColors) !== names(darkColors)) throw new Error("Light and dark semantic colors do not have the same token names");
  const colorConsts = (tokens) => tokens.map((t) => `const val ${camel(t.path.slice(1))}: Long = 0x${argb(t)}`);
  const colorTokensKt = kotlinFile(
    [
      kotlinObject("DdsLightColors", "Semantic colors, light mapping (ARGB).", colorConsts(lightColors)),
      kotlinObject("DdsDarkColors", "Semantic colors, dark mapping (ARGB). Same names as [DdsLightColors].", colorConsts(darkColors)),
    ].join("\n"),
  );

  // --- dimensions ---------------------------------------------------------
  const intConsts = (tokens, depth, prefix = "") =>
    tokens.map((t) => `const val ${ident(prefix, camel(t.path.slice(depth)))}: Int = ${dimension(t)}`);
  const space = take(lightTokens, "space");
  const radius = take(lightTokens, "radius");
  const focus = take(lightTokens, "focus");
  const elevation = lightTokens.filter((t) => t.path[0] === "elevation");
  const nativeGroups = ["touch", "control", "field", "row", "bar", "icon", "border", "screen"].map((group) => ({
    group,
    tokens: take(lightTokens, "native", group),
  }));
  const nativeDocs = {
    touch: "Smallest touch target (dp). `large` applies in large text mode.",
    control: "Button heights (dp, minimums). `sm` is the visible height; its touch area is still [DdsTouch.min].",
    field: "Text field height (dp, minimum).",
    row: "List row heights (dp, minimums).",
    bar: "Top bar and bottom navigation bar heights (dp).",
    icon: "Icon sizes (dp).",
    border: "Stroke widths (dp).",
    screen: "Screen gutters, the width (dp) at which the wide gutter and rail apply, and the gap between blocks.",
  };
  const dimensKt = kotlinFile(
    [
      kotlinObject("DdsSpace", "Spacing scale (dp). The only allowed gaps and paddings.", intConsts(space, 1, "s")),
      kotlinObject("DdsRadius", "Corner radii (dp).", intConsts(radius, 1)),
      kotlinObject("DdsFocus", "Focus ring placement (dp).", intConsts(focus, 1)),
      kotlinObject(
        "DdsElevation",
        "Android elevation (dp) per level.",
        elevation.map((t) => `const val ${ident("level", t.path[1])}: Int = ${wholeNumber(t, t.$value.androidElevation)}`),
      ),
      ...nativeGroups.map(({ group, tokens }) => kotlinObject(`Dds${pascal([group])}`, nativeDocs[group], intConsts(tokens, 2))),
    ].join("\n"),
  );

  // --- typography ---------------------------------------------------------
  const typo = take(lightTokens, "typo");
  const largeTypo = take(lightTokens, "native", "large-text");
  const typeConsts = (tokens, depth) => tokens.map((t) => `val ${camel(t.path.slice(depth))} = ${typography(t)}`);
  const typeTokensKt = kotlinFile(
    [
      "/** One text style: size and line height in sp, weight 100–900. Size and line height are a set. */",
      "class DdsTypeToken(val fontSize: Int, val lineHeight: Int, val fontWeight: Int)\n",
      kotlinObject("DdsType", "The type scale. No size outside this scale.", typeConsts(typo, 1)),
      kotlinObject("DdsLargeType", "The same styles in large text mode.", typeConsts(largeTypo, 2)),
    ].join("\n"),
  );

  // --- motion -------------------------------------------------------------
  const motionKt = kotlinFile(
    [
      "/** Cubic bezier control points. */",
      "class DdsEasingToken(val x1: Float, val y1: Float, val x2: Float, val y2: Float)\n",
      kotlinObject("DdsMotionTokens", "Durations (ms), easings, list stagger and screen shift (dp).", [
        `const val fastMs: Int = ${millis(one("motion", "duration", "fast"))}`,
        `const val shortMs: Int = ${millis(one("native", "motion", "duration", "short"))}`,
        `const val baseMs: Int = ${millis(one("motion", "duration", "base"))}`,
        `const val slowMs: Int = ${millis(one("motion", "duration", "slow"))}`,
        `val standard = ${easing(one("motion", "easing", "standard"))}`,
        `val enter = ${easing(one("motion", "easing", "enter"))}`,
        `val exit = ${easing(one("motion", "easing", "exit"))}`,
        `val travel = ${easing(one("native", "motion", "easing", "travel"))}`,
        `const val staggerStepMs: Int = ${millis(one("native", "motion", "stagger", "step"))}`,
        `const val staggerLimit: Int = ${count(one("native", "motion", "stagger", "limit"))}`,
        `const val shift: Int = ${dimension(one("native", "motion", "shift"))}`,
        `const val splashHoldMs: Int = ${millis(one("native", "motion", "splash", "hold"))}`,
        `const val splashKeepLimitMs: Int = ${millis(one("native", "motion", "splash", "keep-limit"))}`,
      ]),
    ].join("\n"),
  );

  const infoKt = kotlinFile(
    kotlinObject("DdsTokensInfo", "Where these values came from.", [
      'const val sourcePackage: String = "@devslab/dds-tokens"',
      'const val sourceRepository: String = "https://github.com/devslab-kr/dds"',
      "/** SHA-256 of the token files (tokens/ in the source repository) these values were generated from. */",
      `const val sourceSha256: String = "${sourceSha256}"`,
    ]),
  );

  // Anything left over is a token nobody rendered — fail loudly.
  for (const t of lightTokens) {
    if (!claimed.has(t)) throw new Error(`No Android rendering for $type "${t.$type}" at ${where(t)}`);
  }

  // --- XML resources (splash, window background, system bars) --------------
  const xml = (lines) =>
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${GENERATED_HEADER} Source: tokens/*.json -->\n<resources>\n${lines
      .map((l) => `    ${l}`)
      .join("\n")}\n</resources>\n`;
  const colorRes = (tokens) => tokens.map((t) => `<color name="dds_${snake(t.path)}">#${argb(t)}</color>`);
  const dimenRes = (tokens, depth, group) =>
    tokens.map((t) => `<dimen name="dds_${snake([group, ...t.path.slice(depth)])}">${dimension(t)}dp</dimen>`);
  // Whether the page is light, for `android:windowLightStatusBar` /
  // `windowLightNavigationBar` in a theme: dark bar icons on a light page.
  const lightBars = (value) => `<bool name="dds_light_system_bars">${value}</bool>`;
  const valuesXml = xml([
    ...colorRes(lightColors),
    ...dimenRes(space, 1, "space"),
    ...dimenRes(radius, 1, "radius"),
    ...nativeGroups.flatMap(({ group, tokens }) => dimenRes(tokens, 2, group)),
    `<integer name="dds_motion_fast">${millis(one("motion", "duration", "fast"))}</integer>`,
    `<integer name="dds_motion_short">${millis(one("native", "motion", "duration", "short"))}</integer>`,
    `<integer name="dds_motion_base">${millis(one("motion", "duration", "base"))}</integer>`,
    `<integer name="dds_motion_slow">${millis(one("motion", "duration", "slow"))}</integer>`,
    lightBars(true),
  ]);
  // Night carries only the colors that differ from light. A color that is the
  // same in both themes (the brand fill) then has a single definition, so an app
  // that redefines it once in its own res/values rebrands both themes. Were it
  // repeated here, the library night value would win over the app in dark mode.
  const lightArgb = new Map(lightColors.map((t) => [where(t), argb(t)]));
  const nightOnly = darkColors.filter((t) => lightArgb.get(where(t)) !== argb(t));
  const valuesNightXml = xml([...colorRes(nightOnly), lightBars(false)]);

  return new Map([
    [`${KOTLIN_DIR}/DdsColorTokens.kt`, colorTokensKt],
    [`${KOTLIN_DIR}/DdsDimens.kt`, dimensKt],
    [`${KOTLIN_DIR}/DdsTypeTokens.kt`, typeTokensKt],
    [`${KOTLIN_DIR}/DdsMotionTokens.kt`, motionKt],
    [`${KOTLIN_DIR}/DdsTokensInfo.kt`, infoKt],
    [`${RES_DIR}/values/dds_tokens.xml`, valuesXml],
    [`${RES_DIR}/values-night/dds_tokens.xml`, valuesNightXml],
  ]);
}

/** Read tokens/*.json from the repository and render the Android files. */
export function generateAndroidTokens() {
  // Normalize line endings before hashing so the hash does not depend on the
  // checkout (see .gitattributes).
  const text = (file) => readFileSync(join(tokensDir, file), "utf8").replaceAll("\r\n", "\n");
  const hash = createHash("sha256");
  for (const file of [...new Set([...LIGHT_SOURCES, ...DARK_SOURCES])].sort()) hash.update(`${file}\n${text(file)}\n`);
  const parse = (files) => files.map((file) => JSON.parse(text(file)));
  return renderAndroidTokens({ light: parse(LIGHT_SOURCES), dark: parse(DARK_SOURCES), sourceSha256: hash.digest("hex") });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [path, content] of generateAndroidTokens()) {
    const target = join(root, path);
    if (check) {
      let committed = null;
      try {
        committed = readFileSync(target, "utf8").replaceAll("\r\n", "\n");
      } catch {}
      if (committed !== content) stale.push(path);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  if (stale.length > 0) {
    console.error(`android tokens: out of date — run: node scripts/generate-android-tokens.mjs\n${stale.map((p) => `  ${p}`).join("\n")}`);
    process.exit(1);
  }
  console.log(check ? "android tokens: committed files match tokens/*.json" : "android tokens: generated");
}

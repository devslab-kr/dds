/**
 * Android icon generator — packages/dds-icons/svg/*.svg → Compose ImageVectors
 * for android/dds-compose (kr.devslab.dds.compose.icons.DdsIcons).
 *
 *   node scripts/generate-android-icons.mjs           write the file
 *   node scripts/generate-android-icons.mjs --check   fail if the committed file differs
 *
 * One SVG source, as the spec asks (design-system §3.7): the web ships these
 * files, Android ships vectors generated from the same files. Only the core
 * (product) set is generated; the `site-` set is devslab.kr marketing art.
 *
 * Every shape becomes path data. An element or attribute this script does not
 * know is a build error, not a silently dropped line.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const svgDir = join(root, "packages", "dds-icons", "svg");
const OUTPUT = "android/dds-compose/src/main/kotlin/kr/devslab/dds/compose/icons/DdsIcons.kt";

export const GENERATED_ICONS_HEADER = "Generated by scripts/generate-android-icons.mjs — do not edit.";

const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];
const num = (tag, name, file) => {
  const value = Number(attr(tag, name));
  if (!Number.isFinite(value)) throw new Error(`${file}: <${tag}> needs a numeric ${name}`);
  return value;
};
const n = (value) => String(Number(value.toFixed(3)));

/** A circle as two half arcs. */
function circlePath(tag, file) {
  const [cx, cy, r] = ["cx", "cy", "r"].map((k) => num(tag, k, file));
  return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0z`;
}

/** A (rounded) rectangle, clockwise from the top edge. */
function rectPath(tag, file) {
  const [x, y, w, h] = ["x", "y", "width", "height"].map((k) => num(tag, k, file));
  const r = attr(tag, "rx") === undefined ? 0 : num(tag, "rx", file);
  if (r === 0) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
  const arc = (dx, dy) => `a${n(r)} ${n(r)} 0 0 1 ${n(dx)} ${n(dy)}`;
  return `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}${arc(r, r)}v${n(h - 2 * r)}${arc(-r, r)}h${n(-(w - 2 * r))}${arc(-r, -r)}v${n(-(h - 2 * r))}${arc(r, -r)}z`;
}

const pascal = (name) =>
  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

/**
 * @param {{ name: string, svg: string }[]} sources
 * @param {{ mirrorInRtl: string[] }} policy
 * @returns {string} the Kotlin file
 */
export function renderAndroidIcons(sources, policy) {
  const mirrored = new Set(policy.mirrorInRtl);
  let stroke;
  const entries = [];
  for (const { name, svg } of [...sources].sort((a, b) => a.name.localeCompare(b.name))) {
    const open = /<svg\b[^>]*>/.exec(svg)?.[0];
    if (!open) throw new Error(`${name}: not an SVG`);
    if (attr(open, "viewBox") !== "0 0 24 24") throw new Error(`${name}: expected a 24 grid, got viewBox="${attr(open, "viewBox")}"`);
    if (attr(open, "fill") !== "none" || attr(open, "stroke") !== "currentColor") throw new Error(`${name}: expected fill="none" stroke="currentColor"`);
    if (attr(open, "stroke-linecap") !== "round" || attr(open, "stroke-linejoin") !== "round") throw new Error(`${name}: expected round caps and joins`);
    const width = num(open, "stroke-width", name);
    stroke ??= width;
    if (width !== stroke) throw new Error(`${name}: stroke ${width} differs from the set's ${stroke}`);

    const paths = [];
    for (const [tag, element] of svg.slice(open.length).matchAll(/<([a-zA-Z]+)\b[^>]*>/g)) {
      const extra = [...tag.matchAll(/\s([a-zA-Z-]+)="/g)].map((m) => m[1]);
      const allow = { path: ["d"], circle: ["cx", "cy", "r"], rect: ["x", "y", "width", "height", "rx"] }[element];
      if (!allow) throw new Error(`${name}: no Android rendering for <${element}>`);
      const unknown = extra.filter((a) => !allow.includes(a));
      if (unknown.length > 0) throw new Error(`${name}: no Android rendering for ${element} attribute "${unknown[0]}"`);
      if (element === "path") paths.push(attr(tag, "d") ?? (() => { throw new Error(`${name}: <path> without d`); })());
      if (element === "circle") paths.push(circlePath(tag, name));
      if (element === "rect") paths.push(rectPath(tag, name));
    }
    if (paths.length === 0) throw new Error(`${name}: no shapes`);
    entries.push({ name, paths, mirror: mirrored.has(name) });
  }
  for (const name of mirrored) {
    if (!entries.some((e) => e.name === name)) throw new Error(`direction-policy.json names an icon that does not exist: ${name}`);
  }

  const lines = entries.map(({ name, paths, mirror }) => {
    const args = [`"${pascal(name)}"`, ...paths.map((p) => `"${p}"`), ...(mirror ? ["autoMirror = true"] : [])];
    return `    /** \`${name}\`${mirror ? " — mirrored in right-to-left layouts" : ""} */\n    public val ${pascal(name)}: ImageVector by lazy { ddsIcon(${args.join(", ")}) }`;
  });
  return `// ${GENERATED_ICONS_HEADER} Source: packages/dds-icons/svg/*.svg
package kr.devslab.dds.compose.icons

import androidx.compose.ui.graphics.vector.ImageVector

/** Stroke width of the core icon set, in the 24 unit grid. */
internal const val DDS_ICON_STROKE: Float = ${stroke}f

/**
 * The DDS core icons: 24 grid, round caps and joins, drawn in the color of the
 * surrounding content. Names follow the web set (\`chevron-down\` → [ChevronDown]).
 */
public object DdsIcons {
${lines.join("\n\n")}
}
`;
}

/** Read the core SVG set from the repository and render the Kotlin file. */
export function generateAndroidIcons() {
  const sources = readdirSync(svgDir)
    .filter((file) => file.endsWith(".svg"))
    .map((file) => ({ name: file.slice(0, -4), svg: readFileSync(join(svgDir, file), "utf8") }));
  const policy = JSON.parse(readFileSync(join(svgDir, "..", "direction-policy.json"), "utf8"));
  return new Map([[OUTPUT, renderAndroidIcons(sources, policy)]]);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  for (const [path, content] of generateAndroidIcons()) {
    const target = join(root, path);
    if (check) {
      let committed = null;
      try {
        committed = readFileSync(target, "utf8").replaceAll("\r\n", "\n");
      } catch {}
      if (committed !== content) {
        console.error(`android icons: out of date — run: node scripts/generate-android-icons.mjs\n  ${path}`);
        process.exit(1);
      }
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  console.log(check ? "android icons: committed file matches packages/dds-icons/svg" : "android icons: generated");
}
